#!/usr/bin/env bash
# Build the environment and install the launcher, from a fresh clone.
# Resolves everything from its own location, so it works wherever this is cloned.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENV="$HERE/.venv"
LAUNCHER_DIR="${HOME}/.local/bin"
LAUNCHER="${LAUNCHER_DIR}/signal"

say() { printf '\033[36m%s\033[0m\n' "$*"; }
warn() { printf '\033[33m%s\033[0m\n' "$*"; }

say "Signal Arbitrage setup"
say "  project: $HERE"

if ! command -v python3 >/dev/null 2>&1; then
  echo "python3 not found. Install Python 3.11 or newer first." >&2
  exit 1
fi

PY_OK=$(python3 -c 'import sys; print(1 if sys.version_info >= (3, 11) else 0)')
if [ "$PY_OK" != "1" ]; then
  echo "Python 3.11 or newer is required. Found: $(python3 --version)" >&2
  exit 1
fi

say "  creating virtual environment"
python3 -m venv "$VENV"

say "  installing pinned dependencies"
"$VENV/bin/pip" install --quiet --upgrade pip
"$VENV/bin/pip" install --quiet -r "$HERE/requirements.txt"

say "  creating data directories"
mkdir -p "$HERE/data/raw" "$HERE/exports"

say "  installing the 'signal' launcher into $LAUNCHER_DIR"
mkdir -p "$LAUNCHER_DIR"
cat > "$LAUNCHER" <<LAUNCHER_EOF
#!/usr/bin/env bash
# Generated by setup.sh. Regenerate rather than editing.
set -euo pipefail

PROJECT="$HERE"

# Secrets live in the macOS Keychain, never in the repo. Any source config that
# needs a key reads it from the environment, injected here. Add entries with:
#   security add-generic-password -a "\$USER" -s signal-arbitrage-<name> -w
for ITEM in \$(printf '%s\n' \${SIGNAL_KEYCHAIN_ITEMS:-}); do
  VALUE="\$(security find-generic-password -a "\$USER" -s "signal-arbitrage-\$ITEM" -w 2>/dev/null || true)"
  if [ -n "\$VALUE" ]; then
    export "SIGNAL_\$(printf '%s' "\$ITEM" | tr '[:lower:]-' '[:upper:]_')"="\$VALUE"
  fi
done

# Fallback only: a gitignored .env for machines without a Keychain.
if [ -f "\$PROJECT/.env" ]; then
  set -a
  # shellcheck disable=SC1091
  . "\$PROJECT/.env"
  set +a
fi

# python -m resolves against the caller's directory, so the project has to be
# put on the path explicitly or the launcher only works from inside the repo.
export PYTHONPATH="\$PROJECT\${PYTHONPATH:+:\$PYTHONPATH}"

exec "\$PROJECT/.venv/bin/python" -m sigarb.cli "\$@"
LAUNCHER_EOF
chmod +x "$LAUNCHER"

if ! printf '%s' ":$PATH:" | grep -q ":$LAUNCHER_DIR:"; then
  warn "  note: $LAUNCHER_DIR is not on your PATH. Add it to your shell profile."
fi

say ""
say "Done. Run 'signal' from anywhere for the menu, or 'signal --help' for subcommands."
